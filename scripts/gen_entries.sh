#!/usr/bin/env bash
# Regenerate the generated entry_points block of config/overrides.toml (between the BEGIN/END markers):
# switch-case targets outside their jr's function (scripts/jtscan.py) and code pointers in function
# pointer tables with no exported start (unexported_ptrs.py). Run inside nix develop, from the workspace.
set -euo pipefail
cd "$(dirname "$0")/.."
# Per-game values (GAME, ELF_NAME, PS2RECOMP) from tools/game.sh + config/game.env.
ROOT="$PWD"; PS2RECOMP="${PS2RECOMP:-$ROOT/../PS2Recomp}"; . tools/game.sh
P=/home/ivan/PS2/sh3/.venv-oracle/bin/python
$P -I scripts/jtscan.py "disc/$ELF_NAME" "config/$GAME.toml" "config/$GAME.csv" --entries 2>/dev/null | grep '"jt_' > logs/jt_entries.txt
python3 -I "$PS2RECOMP/ps2xRecomp/tools/unexported_ptrs.py" "disc/$ELF_NAME" "config/$GAME.csv" --entries 2>logs/ptr_entries.txt >/dev/null
# config/entries.exclude: one address per line (0x...), pointer-table hits that are really data (SH2: ASCII
# strings at 0x3c43f0..0x3c46f0 decoded as 1088 unhandled instructions). Dropped from both lists.
if [ -s config/entries.exclude ]; then
    pat=$(grep -oE "0x[0-9a-fA-F]+" config/entries.exclude | sed -E "s/^0x0*//" | paste -sd"|")
    for f in logs/jt_entries.txt logs/ptr_entries.txt; do grep -viE "_0*($pat)@" "$f" > "$f.tmp" || true; mv "$f.tmp" "$f"; done
fi
python3 -I - <<'PY'
import re
p = "config/overrides.toml"; s = open(p).read()
body = ("  # BEGIN generated by scripts/gen_entries.sh\n"
        "  # switch-case targets outside the jr's own Ghidra function (Ghidra split the switch):\n"
        + open("logs/jt_entries.txt").read()
        + "  # code addresses in function-pointer tables with no exported start (functions ending in \"b\"):\n"
        + open("logs/ptr_entries.txt").read()
        + "  # END generated\n")
if "# BEGIN generated" in s:
    s = re.sub(r"  # BEGIN generated.*?  # END generated\n", lambda m: body, s, flags=re.S)
else:
    s = re.sub(r"(entry_points = \[\n)(.*?)(\]\n)", lambda m: m.group(1) + body + m.group(3), s, count=1, flags=re.S)
open(p, "w").write(s)
print(len(open("logs/jt_entries.txt").read().splitlines()), "switch entries,",
      len(open("logs/ptr_entries.txt").read().splitlines()), "pointer entries")
PY
